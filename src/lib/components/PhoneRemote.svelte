<script lang="ts">
  import { onMount } from 'svelte';
  import { api, type RemoteInfo } from '../api';
  import { t as tr } from '../i18n.svelte';
  import Toggle from './Toggle.svelte';

  let info = $state<RemoteInfo>({ running: false, url: null, qr_svg: null, error: null });
  let busy = $state(false);
  let copied = $state(false);

  onMount(() => {
    api.remoteStatus().then((i) => (info = i)).catch(() => {});
  });

  async function set(on: boolean) {
    busy = true;
    try {
      if (on) info = await api.remoteStart();
      else {
        await api.remoteStop();
        info = { running: false, url: null, qr_svg: null, error: null };
      }
    } catch (e) {
      info = { running: false, url: null, qr_svg: null, error: String(e) };
    } finally {
      busy = false;
    }
  }

  async function copyUrl() {
    if (!info.url) return;
    try {
      await navigator.clipboard.writeText(info.url);
      copied = true;
      setTimeout(() => (copied = false), 1600);
    } catch { /* ignore */ }
  }
</script>

<div class="set-row">
  <span class="lb">{tr('Phone remote')}
    <span class="set-meta">{tr("Control Tarn from your phone's browser on the same Wi-Fi. Stays on until you turn it off")}</span>
  </span>
  <Toggle checked={info.running} disabled={busy} label={tr('Phone remote')} onchange={(v) => set(v)} />
</div>
{#if info.error}
  <p class="t-meta pr-err">{info.error}</p>
{/if}
{#if info.running && info.qr_svg}
  <div class="pr">
    <!-- SVG is generated by Tarn's backend from the URL, not user content. -->
    <div class="pr-qr" aria-label="QR code for the phone remote">{@html info.qr_svg}</div>
    <div class="pr-txt">
      <b>{tr('Scan with your phone camera')}</b>
      <span class="t-meta">{tr('Search songs, control playback, queue and lyrics. Same Wi-Fi only.')}</span>
      <button class="pr-url" type="button" onclick={copyUrl} title={tr('Copy link')}>
        {info.url}
      </button>
      <span class="t-meta">{copied ? tr('Copied') : tr('Anyone with this link on your network can control playback. Turning the remote off and on makes a new link.')}</span>
    </div>
  </div>
{/if}

