<script lang="ts">
  import { onMount } from 'svelte';
  import { api, type RemoteInfo } from '../api';
  import Toggle from './Toggle.svelte';

  let info = $state<RemoteInfo>({ running: false, url: null, qr_svg: null, error: null });
  let busy = $state(false);

  onMount(() => {
    api.remoteStatus().then((i) => (info = i)).catch(() => {});
  });

  async function set(on: boolean) {
    busy = true;
    try {
      if (on) info = await api.remoteStart();
      else {
        await api.remoteStop();
        info = { running: false, url: null, qr_svg: null, error: null };
      }
    } catch (e) {
      info = { running: false, url: null, qr_svg: null, error: String(e) };
    } finally {
      busy = false;
    }
  }
</script>

<div class="set-row">
  <span class="lb">Phone remote
    <span class="t-meta" style="display:block;font-weight:450;margin-top:2px">Control Tarn from your phone's browser on the same Wi-Fi. Turns off when Tarn closes</span>
  </span>
  <Toggle checked={info.running} disabled={busy} label="Phone remote" onchange={(v) => set(v)} />
</div>
{#if info.error}
  <p class="t-meta pr-err">{info.error}</p>
{/if}
{#if info.running && info.qr_svg}
  <div class="pr">
    <!-- SVG is generated by Tarn's backend from the URL, not user content. -->
    <div class="pr-qr" aria-label="QR code for the phone remote">{@html info.qr_svg}</div>
    <div class="pr-txt">
      <b>Scan with your phone camera</b>
      <span class="t-meta">Or open this link on a device on the same network:</span>
      <code class="pr-url">{info.url}</code>
      <span class="t-meta">Anyone with this link on your network can control playback. Turning the remote off and on makes a new link.</span>
    </div>
  </div>
{/if}

